#!/usr/bin/env python3
"""
Jellyfin Auth - Exchange a Jellyfin login for a long-lived access token.

Run this once. It prompts for your password, trades it for an access token via
the Jellyfin API, and saves only the token to .env. The password is never
written to disk and never leaves this process.

A regular (non-admin) user token is sufficient for the transcript pipeline:
item lookup, subtitle download, and audio streaming.

Usage:
    python scripts/jellyfin-auth.py

    # Non-interactive server/user (still prompts for password)
    python scripts/jellyfin-auth.py --url https://jellyfin.example.com --user spencer
"""

import argparse
import getpass
import json
import socket
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Dict

CLIENT_NAME = "Scriptdle"
CLIENT_VERSION = "1.0.0"


def get_repo_root() -> Path:
    """Get the scriptdle repository root directory."""
    return Path(__file__).parent.parent


def load_env() -> Dict[str, str]:
    """Load environment variables from .env file."""
    env_file = get_repo_root() / ".env"
    env_vars = {}
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            env_vars[key.strip()] = value.strip().strip('"').strip("'")
    return env_vars


def save_env(updates: Dict[str, str]) -> Path:
    """Merge updates into .env, preserving existing keys, comments, and order."""
    env_file = get_repo_root() / ".env"
    lines = env_file.read_text().splitlines() if env_file.exists() else []

    remaining = dict(updates)
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key = stripped.split("=", 1)[0].strip()
        if key in remaining:
            lines[i] = f"{key}={remaining.pop(key)}"

    if remaining:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append("# Jellyfin (generated by scripts/jellyfin-auth.py)")
        lines.extend(f"{k}={v}" for k, v in remaining.items())

    env_file.write_text("\n".join(lines) + "\n")
    env_file.chmod(0o600)
    return env_file


def device_id() -> str:
    """Stable per-machine device id so we don't spawn a new session each run."""
    return f"scriptdle-{socket.gethostname()}"


def api_request(url: str, auth_header: str, payload: dict = None) -> dict:
    """Make a Jellyfin API request, returning the decoded JSON response."""
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(url, data=data, method="POST" if data else "GET")
    request.add_header("Authorization", auth_header)
    request.add_header("Content-Type", "application/json")

    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read())


def authenticate(base_url: str, username: str, password: str) -> dict:
    """Trade username/password for an access token."""
    auth_header = (
        f'MediaBrowser Client="{CLIENT_NAME}", Device="{CLIENT_NAME}", '
        f'DeviceId="{device_id()}", Version="{CLIENT_VERSION}"'
    )
    return api_request(
        f"{base_url}/Users/AuthenticateByName",
        auth_header,
        {"Username": username, "Pw": password},
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Authenticate with Jellyfin")
    parser.add_argument("--url", help="Jellyfin server URL")
    parser.add_argument("--user", help="Jellyfin username")
    args = parser.parse_args()

    env = load_env()
    base_url = args.url or env.get("JELLYFIN_URL") or input("Jellyfin server URL: ")
    base_url = base_url.strip().rstrip("/")
    if not base_url.startswith(("http://", "https://")):
        base_url = f"https://{base_url}"

    username = args.user or env.get("JELLYFIN_USER") or input("Jellyfin username: ")
    username = username.strip()

    print(f"\nAuthenticating {username} against {base_url}")
    print("Your password is used once for this request and is not saved.\n")
    password = getpass.getpass("Jellyfin password: ")

    try:
        result = authenticate(base_url, username, password)
    except urllib.error.HTTPError as e:
        if e.code == 401:
            print("\nError: Jellyfin rejected those credentials.", file=sys.stderr)
        else:
            print(f"\nError: Jellyfin returned HTTP {e.code}: {e.reason}", file=sys.stderr)
        return 1
    except (urllib.error.URLError, TimeoutError) as e:
        print(f"\nError: Could not reach {base_url}: {e}", file=sys.stderr)
        return 1
    finally:
        del password

    token = result.get("AccessToken")
    user_id = (result.get("User") or {}).get("Id")
    if not token or not user_id:
        print("\nError: Jellyfin response did not include a token.", file=sys.stderr)
        return 1

    env_file = save_env({
        "JELLYFIN_URL": base_url,
        "JELLYFIN_USER": username,
        "JELLYFIN_TOKEN": token,
        "JELLYFIN_USER_ID": user_id,
    })

    print(f"\nSaved token to {env_file} (gitignored, mode 600)")
    print("Revoke any time from Jellyfin under Profile > Devices.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
